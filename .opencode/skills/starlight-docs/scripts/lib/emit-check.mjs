/**
 * starlight-docs — export the assertions as a standalone script.
 *
 * This module does not re-implement any check: it reads `check.mjs`, strips the
 * `export` keywords and appends a small runner with the repo-specific values
 * inlined. The result is a one-way snapshot — re-export after upgrading the
 * skill.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { CHECK_VERSION } from './check.mjs'

const CHECK_SOURCE = fileURLToPath(new URL('./check.mjs', import.meta.url))

export function buildStandalone(options) {
  let source = fs.readFileSync(CHECK_SOURCE, 'utf8')
  if (/^\s*import\s+[^'"]*from\s+['"]\./m.test(source)) {
    throw new Error('check.mjs must not import relative modules; it is exported verbatim')
  }
  source = source.replace(/^export\s+/gm, '')

  const header = [
    '#!/usr/bin/env node',
    '// Generated by starlight-docs (--action emit-check). Do not edit by hand.',
    `// Assertion snapshot v${CHECK_VERSION}. Re-export after upgrading the skill:`,
    '//   node <skill>/scripts/site.mjs --action emit-check --repo <repo> --out <this file>',
    '// Only Node is required; the values below are inlined at export time.',
    '',
  ].join('\n')

  const runner = [
    '',
    `const INLINED = ${JSON.stringify(options, null, 2)}`,
    '',
    'function parseArgs(argv) {',
    '  const args = {}',
    '  for (let index = 0; index < argv.length; index += 1) {',
    '    const token = argv[index]',
    "    if (!token.startsWith('--')) continue",
    "    const [key, inline] = token.slice(2).split('=')",
    '    if (inline !== undefined) args[key] = inline',
    "    else if (argv[index + 1] && !argv[index + 1].startsWith('--')) { args[key] = argv[index + 1]; index += 1 }",
    '    else args[key] = true',
    '  }',
    '  return args',
    '}',
    '',
    'const args = parseArgs(process.argv.slice(2))',
    'const options = {',
    '  ...INLINED,',
    '  ...(args.dist ? { dist: args.dist } : {}),',
    '  ...(args.base !== undefined ? { base: args.base } : {}),',
    '  ...(args.profile ? { profile: args.profile } : {}),',
    '}',
    '',
    'const result = checkDist(options)',
    'const text = formatFindingsText(result.findings)',
    'if (text) console.log(text)',
    "const errors = result.findings.filter((item) => item.severity === 'error').length",
    'if (errors === 0) {',
    "  console.log('ok: ' + result.stats.routes + ' routes, ' + result.stats.linksChecked + ' links checked')",
    '} else {',
    "  console.log(errors + ' error(s)')",
    '}',
    'process.exitCode = errors === 0 ? 0 : 1',
    '',
  ].join('\n')

  return `${header}${source}\n${runner}`
}

export function emitCheck({ out, options, dryRun }) {
  const content = buildStandalone(options)
  const absolute = path.resolve(out)
  if (!dryRun) {
    fs.mkdirSync(path.dirname(absolute), { recursive: true })
    fs.writeFileSync(absolute, content, 'utf8')
  }
  return { path: absolute, bytes: Buffer.byteLength(content, 'utf8'), dryRun: Boolean(dryRun), content }
}
